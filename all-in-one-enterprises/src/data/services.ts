export function getServiceBySlug(slug: string): AioService | undefined {
  return aioServices.find((s) => s.slug === slug);
}

export function getServicesByDivision(division: ServiceDivision): AioService[] {
  return aioServices.filter((s) => s.division === division);
}

export function isDivisionSlug(slug: string): boolean {
  return DIVISION_SLUGS.has(slug);
}

