/*
 * AIO OFFICE unified review — INTAKE. The approved client-migration experience is not redesigned: the INTAKE root
 * carries the approved root's own modules (hero, the three paths, migration status, file types, providers, the security
 * panel, START MIGRATION) inside the office frame, and every flow step is the approved authority screen itself
 * (AIO_CLIENT_MIGRATION_AUTHORITY, 41 screens). What is new is the staff working layer around it: the ten INTAKE sections
 * and a case page per migration. Staff preparation stops at PREBUILT; only the client's confirmation makes a client ACTIVE.
 * MIG_SCREENS is generated by build.mjs from AIO_CLIENT_MIGRATION_AUTHORITY/authority-manifest.json.
 */
const MIG_FLOW_ARTIFACT = 'https://claude.ai/artifact/1rPbngoDNkMNwTg695HUZQ';
const MIG_BRANCH = {
  existing: ['EXISTING CLIENT FILE', 'IMPORT CURRENT RECORDS FROM ANOTHER PROVIDER OR A PREVIOUS SYSTEM.', 'path-existing.jpg', 'migrate'],
  new: ['NEW CLIENT FILE', 'START FRESH AND UPLOAD RECORDS TO AIO.', 'path-new.jpg', 'person-plus'],
  bulk: ['BULK BATCH MIGRATION', 'IMPORT MULTIPLE CLIENTS AT ONCE (FOR FLEETS OR ACCOUNTANTS).', 'path-bulk.jpg', 'database'],
  activation: ['CLIENT ACTIVATION', 'WHAT THE CLIENT SEES IN THEIR OWN OFFICE WHEN THEY CONFIRM. STAFF NEVER CONFIRM FOR THEM.', null, 'profile'],
};
const INTAKE_SECTIONS = [
  ['existing', 'EXISTING CLIENT FILE', 'migrate', 'A CURRENT CLIENT’S RECORDS FROM ANOTHER PROVIDER.'],
  ['new', 'NEW CLIENT FILE', 'person-plus', 'A NEW CLIENT, FROM THEIR UPLOADS.'],
  ['bulk', 'BULK BATCH MIGRATION', 'database', 'MANY CLIENTS AT ONCE.'],
  ['status', 'MIGRATION STATUS', 'time-log', 'EVERY CASE AND WHERE IT STANDS.'],
  ['extraction', 'EXTRACTION & CLASSIFICATION', 'search-file', 'WHAT AIO READ FROM THE FILES.'],
  ['match', 'MATCH & RECONCILE', 'filter', 'DUPLICATES AND CONFLICTS TO SETTLE.'],
  ['review', 'FOUNDER REVIEW', 'security', 'APPROVAL LANDS ON PREBUILT — NEVER ACTIVE.'],
  ['prebuilt', 'PREBUILT CLIENTS', 'company', 'PREPARED BY STAFF, NOT ACTIVE.'],
  ['activation', 'ACTIVATION & INVITES', 'letter', 'THE CLIENT CONFIRMS IN THEIR OWN OFFICE.'],
  ['history', 'MIGRATION HISTORY', 'history', 'COMPLETED MIGRATIONS.'],
];
const migStatus = (m) => SESSION.status[`mig:${m.id}`] ?? m.stage;
const migLife = (m) => SESSION.status[`miglife:${m.id}`]?.[0] ?? m.life;
const migIdx = (life) => MIG_LIFE.findIndex(([k]) => k === life);
const branchScreens = (b) => MIG_SCREENS.filter((s) => s.branch === b);
const screenAt = (id) => {
  const s = MIG_SCREENS.find((x) => x.id === id);
  return s ? [s.branch, branchScreens(s.branch).indexOf(s)] : ['existing', 0];
};
const GATE = `<div class="gate">${ico('lock')}<div><b>STAFF PREPARATION DOES NOT MAKE A CLIENT ACTIVE.</b><span>APPROVAL LANDS A CLIENT ON PREBUILT. THE CLIENT IS INVITED AND CONFIRMS THEIR OWN INFORMATION — ONLY THAT CONFIRMATION MAKES THEM ACTIVE.</span></div></div>`;
const caseRow = (m) => ({ go: `intake/case/${m.id}`, lead: icoTile(MIG_BRANCH[m.branch][3]), title: m.name, sub: `${MIG_BRANCH[m.branch][0]} · ${m.files} FILES · ${m.source}`, meta: `${staffName(m.owner)} · STARTED ${m.started}`, status: migStatus(m) });

function intakePage(r) {
  const [, a, b, c] = r.seg;
  if (!a) return intakeRoot();
  if (a === 'case') return intakeCase(b, r);
  if (a === 'flow') return flowViewer(b, Number(c) || 0, r);
  if (INTAKE_SECTIONS.some(([k]) => k === a)) return intakeSection(a);
  return missing(r);
}

