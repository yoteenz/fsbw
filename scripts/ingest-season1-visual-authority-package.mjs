#!/usr/bin/env node
/**
 * Copies Cursor-light visual authority package into public/ and emits TS asset registry.
 * Usage: node scripts/ingest-season1-visual-authority-package.mjs <extracted-sw_team_organized_light>
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'fs';
import { basename, dirname, join } from 'path';

const srcRoot = process.argv[2];
if (!srcRoot || !existsSync(join(srcRoot, 'manifest.json'))) {
  console.error('Usage: node scripts/ingest-season1-visual-authority-package.mjs <sw_team_organized_light dir>');
  process.exit(1);
}

const manifest = JSON.parse(readFileSync(join(srcRoot, 'manifest.json'), 'utf8'));
const publicRoot = join(process.cwd(), 'public/studio-world/residents/season-1');
const docsManifestOut = join(
  process.cwd(),
  'docs/studio-world/residents/season-1/visual-authority-package-manifest.json'
);

const slugById = {
  'SW-RESIDENT-001': 'sw-resident-001-etta-vale',
  'SW-RESIDENT-002': 'sw-resident-002-zuri-xu',
  'SW-RESIDENT-003': 'sw-resident-003-jules-mercer',
  'SW-RESIDENT-004': 'sw-resident-004-noa-kline',
  'SW-RESIDENT-005': 'sw-resident-005-caspian-reed',
  'SW-RESIDENT-006': 'sw-resident-006-iona-wells',
  'SW-RESIDENT-007': 'sw-resident-007-marlowe-saint',
  'SW-RESIDENT-008': 'sw-resident-008-elio-vahn',
};

const closeupCounters = {};

function normalizedName(record) {
  const slug = slugById[record.resident_id];
  const path = record.organized_path;
  if (path.includes('01-natural-authority')) {
    return `${slug}-natural-fullbody-01.jpg`;
  }
  if (path.includes('03-work-uniform-candidates')) {
    return `${slug}-work-uniform-candidate-01.jpg`;
  }
  if (path.includes('04-alternate-modes')) {
    return `${slug}-alternate-mode-01.jpg`;
  }
  if (path.includes('02-closeups')) {
    const key = record.resident_id;
    closeupCounters[key] = (closeupCounters[key] ?? 0) + 1;
    const n = String(closeupCounters[key]).padStart(2, '0');
    return `${slug}-closeup-${n}.jpg`;
  }
  return basename(path);
}

function folderCategory(organizedPath) {
  if (organizedPath.includes('01-natural-authority')) return 'natural-authority';
  if (organizedPath.includes('02-closeups')) return 'closeups';
  if (organizedPath.includes('03-work-uniform-candidates')) return 'work-uniform-candidates';
  if (organizedPath.includes('04-alternate-modes')) return 'alternate-modes';
  return 'other';
}

const assets = [];

for (const record of manifest.records) {
  const slug = slugById[record.resident_id];
  if (!slug) throw new Error(`Unknown resident ${record.resident_id}`);
  const fileName = normalizedName(record);
  const relDir = join(slug, folderCategory(record.organized_path));
  const destDir = join(publicRoot, relDir);
  mkdirSync(destDir, { recursive: true });
  const destFile = join(destDir, fileName);
  const srcFile = join(srcRoot, record.organized_path);
  if (!existsSync(srcFile)) throw new Error(`Missing source file ${srcFile}`);
  copyFileSync(srcFile, destFile);

  const publicPath = `/studio-world/residents/season-1/${relDir.replace(/\\/g, '/')}/${fileName}`;
  const assetId = `swa:${record.resident_id}:${folderCategory(record.organized_path)}:${fileName}`;
  assets.push({
    assetId,
    residentId: record.resident_id,
    residentName: record.resident_name,
    publicPath,
    repoPath: `public/studio-world/residents/season-1/${relDir.replace(/\\/g, '/')}/${fileName}`,
    sourceFilename: record.source_filename,
    organizedPath: record.organized_path,
    packageStatus: record.status,
    category: folderCategory(record.organized_path),
    sourcePackage: 'STUDIO_WORLD_SEASON1_VISUAL_AUTHORITY_CURSOR_LIGHT_v1',
  });
}

writeFileSync(docsManifestOut, JSON.stringify({ ...manifest, ingestedAt: new Date().toISOString() }, null, 2) + '\n');

const tsOut = join(
  process.cwd(),
  'src/studio-os-core/studio-world-residents/visual-authority/season1-ingested-assets.generated.ts'
);

const ts = `/** AUTO-GENERATED by scripts/ingest-season1-visual-authority-package.mjs — do not hand-edit */
import type { ResidentId } from '../types';

export type Season1PackageAssetStatus =
  | 'FOUNDER_APPROVED'
  | 'FOUNDER_APPROVED_REFERENCE'
  | 'REFERENCE_ONLY'
  | 'CONCEPT_REFERENCE_ONLY'
  | 'ALTERNATE_MODE_REFERENCE';

export type Season1IngestedVisualAsset = {
  assetId: string;
  residentId: ResidentId;
  residentName: string;
  publicPath: string;
  repoPath: string;
  sourceFilename: string;
  organizedPath: string;
  packageStatus: Season1PackageAssetStatus;
  category: 'natural-authority' | 'closeups' | 'work-uniform-candidates' | 'alternate-modes' | 'other';
  sourcePackage: 'STUDIO_WORLD_SEASON1_VISUAL_AUTHORITY_CURSOR_LIGHT_v1';
};

export const SEASON1_INGESTED_VISUAL_ASSETS: Season1IngestedVisualAsset[] = ${JSON.stringify(assets, null, 2)} as Season1IngestedVisualAsset[];

export const SEASON1_VISUAL_ASSET_BY_ID: Record<string, Season1IngestedVisualAsset> = Object.fromEntries(
  SEASON1_INGESTED_VISUAL_ASSETS.map((a) => [a.assetId, a])
);
`;

writeFileSync(tsOut, ts);
console.log(`Ingested ${assets.length} assets into public/studio-world/residents/season-1/`);
console.log(`Wrote ${tsOut}`);
