#!/usr/bin/env node
/**
 * Package Studio DNA Capsule™ — versioned releases + stable latest.zip alias.
 * Companion to AI Context Capsule (WHAT vs HOW).
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execSync } from 'node:child_process';

const ROOT = path.resolve(import.meta.dirname, '..');

const CANONICAL_CAPSULE_VERSION = '1.0.0';
const GENERATOR_VERSION = '1.0.0';
const LATEST_ALIAS = 'latest.zip';
const RELEASE_MANIFEST = 'release.json';
const METADATA_FILE = 'studio-dna-capsule.json';
const DOWNLOAD_BASE = '/downloads/studio-dna-capsules';

const REQUIRED_FILES = [
  'README_FIRST.md',
  'MANIFEST.md',
  'RELATIONSHIP_TO_CONTEXT_CAPSULE.md',
  'FOUNDER_DESIGN_PHILOSOPHY.md',
  'ARCHITECTURE_DNA.md',
  'CREATIVE_DIRECTION_DNA.md',
  'FOUNDER_DECISION_PATTERNS.md',
  'COMMUNICATION_DNA.md',
  'QUALITY_STANDARDS.md',
  'INSTITUTIONAL_VALUES.md',
  'AI_COLLABORATION_DNA.md',
  'CANON_PRESERVATION_POLICY.md',
  'CANON_REGISTRY.md',
  'EVOLUTION.md',
];

const READING_ORDER = [
  'README_FIRST.md',
  'MANIFEST.md',
  'RELATIONSHIP_TO_CONTEXT_CAPSULE.md',
  'CANON_PRESERVATION_POLICY.md',
  'FOUNDER_DESIGN_PHILOSOPHY.md',
  'ARCHITECTURE_DNA.md',
  'CREATIVE_DIRECTION_DNA.md',
  'FOUNDER_DECISION_PATTERNS.md',
  'COMMUNICATION_DNA.md',
  'QUALITY_STANDARDS.md',
  'INSTITUTIONAL_VALUES.md',
  'AI_COLLABORATION_DNA.md',
  'CANON_REGISTRY.md',
  'EVOLUTION.md',
  'DNA_VALIDATION.md',
];

function findCapsuleDir() {
  const dirs = fs
    .readdirSync(ROOT, { withFileTypes: true })
    .filter((e) => e.isDirectory() && /^StudioOS_StudioDNACapsule_v/i.test(e.name))
    .map((e) => e.name)
    .sort();
  if (!dirs.length) throw new Error('No StudioOS_StudioDNACapsule_v* directory at repo root.');
  return { dir: path.join(ROOT, dirs[dirs.length - 1]), name: dirs[dirs.length - 1] };
}

function readVersion(capsuleDir) {
  const manifestPath = path.join(capsuleDir, 'MANIFEST.md');
  if (fs.existsSync(manifestPath)) {
    const manifest = fs.readFileSync(manifestPath, 'utf8');
    const match = manifest.match(/\*\*Capsule Version\*\*\s*\|\s*([^\|\n]+)/);
    if (match) return match[1].trim();
  }
  return CANONICAL_CAPSULE_VERSION;
}

function readingOrderChecksum() {
  return crypto.createHash('sha256').update(READING_ORDER.join('\n')).digest('hex');
}

function readGitCommit() {
  try {
    return execSync('git rev-parse HEAD', { cwd: ROOT, encoding: 'utf8' }).trim();
  } catch {
    return 'unknown';
  }
}

function validate(capsuleDir, version) {
  const presentMd = fs.readdirSync(capsuleDir).filter((f) => f.endsWith('.md'));
  const presentSet = new Set(presentMd);
  const missing = REQUIRED_FILES.filter((f) => !presentSet.has(f));
  if (missing.length) {
    console.error('\n❌ Studio DNA Capsule validation failed — missing:\n');
    for (const f of missing) console.error(`   • ${f}`);
    process.exit(1);
  }
  if (version !== CANONICAL_CAPSULE_VERSION) {
    console.error(`\n❌ DNA Capsule version must be ${CANONICAL_CAPSULE_VERSION}; found ${version}\n`);
    process.exit(1);
  }
  for (const doc of READING_ORDER.filter((f) => f !== 'DNA_VALIDATION.md')) {
    if (!fs.existsSync(path.join(capsuleDir, doc))) {
      console.error(`\n❌ Reading order missing: ${doc}\n`);
      process.exit(1);
    }
  }
  return presentMd;
}

function writeDnaValidation(capsuleDir, version, generatedAt, gitCommit, checksum, presentMd) {
  const body = `# DNA Capsule Validation — Auto-Generated

| Field | Value |
|-------|-------|
| **Capsule Version** | ${version} |
| **Capsule Type** | Studio DNA Capsule™ |
| **Generated (UTC)** | ${generatedAt} |
| **Git Commit** | ${gitCommit} |
| **Validation** | pass |
| **Documents** | ${REQUIRED_FILES.length} required |
| **Reading Order Hash** | ${checksum} |
| **Markdown files on disk** | ${presentMd.length} |

## Companion artifact

Pair with **AI Context Capsule™** v0.3.1 for complete onboarding (WHAT + HOW).

## Checks

- ✓ All required DNA documents present
- ✓ CANON_PRESERVATION_POLICY.md included (Section 21)
- ✓ Version matches manifest
- ✓ latest.zip updated only after validation pass

*Do not edit manually — regenerated by \`scripts/package-studio-dna-capsule-zip.mjs\`.*
`;
  fs.writeFileSync(path.join(capsuleDir, 'DNA_VALIDATION.md'), body);
}

function writeMetadata(capsuleDir, capsuleFolderName, version, generatedAt) {
  const payload = {
    schemaVersion: 1,
    capsuleType: 'studio-dna',
    capsuleVersion: version,
    manifestVersion: version,
    capsuleFolder: capsuleFolderName,
    generatedAt,
    companionCapsule: { type: 'ai-context', version: '0.3.1' },
    documentCount: REQUIRED_FILES.length,
    readingOrder: READING_ORDER,
    readingOrderChecksum: readingOrderChecksum(),
    requiredMarkdownFiles: REQUIRED_FILES,
    validationStatus: 'pass',
    generatorVersion: GENERATOR_VERSION,
  };
  fs.writeFileSync(path.join(capsuleDir, METADATA_FILE), JSON.stringify(payload, null, 2) + '\n');
  return payload;
}

function sha256File(filePath) {
  return crypto.createHash('sha256').update(fs.readFileSync(filePath)).digest('hex');
}

function writeJson(outPath, payload) {
  fs.writeFileSync(outPath, JSON.stringify(payload, null, 2) + '\n');
}

function packageCapsule() {
  const { dir: capsuleDir, name: capsuleFolderName } = findCapsuleDir();
  const version = readVersion(capsuleDir);
  const fileName = `StudioOS_StudioDNACapsule_v${version}.zip`;
  const presentMd = validate(capsuleDir, version);

  const generatedAt = new Date().toISOString();
  const gitCommit = readGitCommit();
  const orderChecksum = readingOrderChecksum();
  writeMetadata(capsuleDir, capsuleFolderName, version, generatedAt);
  writeDnaValidation(capsuleDir, version, generatedAt, gitCommit, orderChecksum, presentMd);

  const publicOut = path.join(ROOT, 'public/downloads/studio-dna-capsules');
  const releasesOut = path.join(ROOT, 'releases/downloads/studio-dna-capsules');
  fs.mkdirSync(publicOut, { recursive: true });
  fs.mkdirSync(releasesOut, { recursive: true });

  const publicZip = path.join(publicOut, fileName);
  execSync(`zip -r -q ${JSON.stringify(publicZip)} ${JSON.stringify(capsuleFolderName)}`, {
    cwd: ROOT,
    stdio: 'inherit',
  });

  const checksumSha256 = sha256File(publicZip);
  const stat = fs.statSync(publicZip);
  const versionedDownloadPath = `${DOWNLOAD_BASE}/${fileName}`;
  const latestDownloadPath = `${DOWNLOAD_BASE}/${LATEST_ALIAS}`;

  fs.copyFileSync(publicZip, path.join(publicOut, LATEST_ALIAS));
  fs.copyFileSync(publicZip, path.join(releasesOut, fileName));
  fs.copyFileSync(publicZip, path.join(releasesOut, LATEST_ALIAS));

  const releaseManifest = {
    schemaVersion: 1,
    capsuleType: 'studio-dna',
    currentVersion: version,
    generatedAt,
    gitCommit,
    validationStatus: 'pass',
    documentCount: REQUIRED_FILES.length,
    checksumSha256,
    generatorVersion: GENERATOR_VERSION,
    artifact: fileName,
    latestAlias: LATEST_ALIAS,
    latestDownloadPath,
    versionedDownloadPath,
  };

  writeJson(path.join(publicOut, RELEASE_MANIFEST), releaseManifest);
  writeJson(path.join(releasesOut, RELEASE_MANIFEST), releaseManifest);

  const apiBuildManifest = {
    schemaVersion: 1,
    capsuleType: 'studio-dna',
    artifact: fileName,
    capsuleVersion: version,
    generatedAt,
    fileCount: REQUIRED_FILES.length,
    checksumSha256,
    sizeBytes: stat.size,
    downloadPath: versionedDownloadPath,
    latestDownloadPath,
    versionedDownloadPath,
    generatorVersion: GENERATOR_VERSION,
    validationStatus: 'pass',
  };
  writeJson(path.join(ROOT, 'api/_lib/studio-dna-capsule-build-manifest.json'), apiBuildManifest);
  writeJson(path.join(ROOT, 'api/_lib/studio-dna-capsule-release.json'), releaseManifest);

  console.log(`\nStudio DNA Capsule™ packaged:`);
  console.log(`  Capsule Version:  ${version}`);
  console.log(`  Generated:        ${generatedAt}`);
  console.log(`  Validation:       pass`);
  console.log(`  Required docs:    ${REQUIRED_FILES.length}`);
  console.log(`  Versioned:        ${versionedDownloadPath} (${(stat.size / 1024).toFixed(1)} KB)`);
  console.log(`  Latest:           ${latestDownloadPath}\n`);
}

packageCapsule();
