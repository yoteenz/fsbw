#!/usr/bin/env node
/**
 * Sync BCF video batch manifest → public/assets/bcf/videos/manifest.json
 * and src/utils/bcfPdpHeroVideos.generated.ts for the storefront.
 *
 * Committed files store storage paths only (no Supabase URLs) — resolved at runtime.
 *
 * Usage:
 *   node scripts/bcf/sync-bcf-video-manifest.mjs
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..', '..');
const BATCH_MANIFEST = join(__dirname, 'manifests', 'bcf-videos-v1.json');
const PUBLIC_MANIFEST = join(ROOT, 'public/assets/bcf/videos/manifest.json');
const GENERATED_TS = join(ROOT, 'src/utils/bcfPdpHeroVideos.generated.ts');

function videoEntry(row) {
  const mp4StoragePath = row.hasMp4
    ? row.mp4StoragePath
    : row.status === 'ready_legacy'
      ? row.legacyVideoStoragePath
      : null;
  const webmStoragePath = row.hasWebm ? row.webmStoragePath : null;
  if (!mp4StoragePath && !webmStoragePath) return null;
  return {
    mp4StoragePath,
    webmStoragePath,
    status: row.status,
    productKey: row.productKey,
    category: row.category,
    texture: row.texture,
    colorId: row.colorId,
  };
}

function main() {
  if (!existsSync(BATCH_MANIFEST)) {
    console.error('Missing batch manifest:', BATCH_MANIFEST);
    process.exit(1);
  }

  const batch = JSON.parse(readFileSync(BATCH_MANIFEST, 'utf8'));
  const videos = {};
  for (const row of batch.items || []) {
    if (row.status === 'missing' || row.status === 'failed') continue;
    const entry = videoEntry(row);
    if (entry) videos[row.productKey] = entry;
  }

  const publicManifest = {
    version: 1,
    updatedAt: new Date().toISOString(),
    promptVersion: batch.promptVersion,
    bucket: batch.bucket,
    storagePrefix: batch.storagePrefix,
    videos,
  };

  mkdirSync(dirname(PUBLIC_MANIFEST), { recursive: true });
  writeFileSync(PUBLIC_MANIFEST, JSON.stringify(publicManifest, null, 2));
  console.log('Wrote', PUBLIC_MANIFEST, `(${Object.keys(videos).length} videos)`);

  const tsBody =
    '/** Auto-generated by scripts/bcf/sync-bcf-video-manifest.mjs — do not edit by hand. */\n' +
    `export const BCF_PDP_HERO_VIDEOS = ${JSON.stringify(videos, null, 2)} as const;\n` +
    `export type BcfPdpHeroVideoEntry = (typeof BCF_PDP_HERO_VIDEOS)[keyof typeof BCF_PDP_HERO_VIDEOS];\n`;
  writeFileSync(GENERATED_TS, tsBody);
  console.log('Wrote', GENERATED_TS);
}

main();
