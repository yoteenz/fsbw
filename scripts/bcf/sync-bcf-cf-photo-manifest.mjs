#!/usr/bin/env node
/**
 * Sync BCF closure/frontal photo batch manifest → public/assets/bcf/photos/manifest.json
 * and src/utils/bcfPdpCfHeroPhotos.generated.ts for the storefront.
 *
 * Committed files store storage paths only (no Supabase URLs) — resolved at runtime.
 *
 * Usage:
 *   node scripts/bcf/sync-bcf-cf-photo-manifest.mjs
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..', '..');
const BATCH_MANIFEST = join(__dirname, 'manifests', 'bcf-cf-photos-v1.json');
const PUBLIC_MANIFEST = join(ROOT, 'public/assets/bcf/photos/manifest.json');
const GENERATED_TS = join(ROOT, 'src/utils/bcfPdpCfHeroPhotos.generated.ts');

function photoEntry(row) {
  if (!row.hasPhoto || !row.photoStoragePath) return null;
  return {
    photoStoragePath: row.photoStoragePath,
    status: row.status,
    productKey: row.productKey,
    category: row.category,
    texture: row.texture,
    colorId: row.colorId,
    ...(row.generatedAt ? { generatedAt: row.generatedAt } : {}),
  };
}

function main() {
  if (!existsSync(BATCH_MANIFEST)) {
    console.error('Missing batch manifest:', BATCH_MANIFEST);
    process.exit(1);
  }

  const batch = JSON.parse(readFileSync(BATCH_MANIFEST, 'utf8'));
  const photos = {};
  for (const row of batch.items || []) {
    if (row.status === 'missing' || row.status === 'failed') continue;
    const entry = photoEntry(row);
    if (entry) photos[row.productKey] = entry;
  }

  const publicManifest = {
    version: 1,
    updatedAt: new Date().toISOString(),
    promptVersion: batch.promptVersion,
    bucket: batch.bucket,
    falModel: batch.falModel,
    photos,
  };

  mkdirSync(dirname(PUBLIC_MANIFEST), { recursive: true });
  writeFileSync(PUBLIC_MANIFEST, JSON.stringify(publicManifest, null, 2));
  console.log('Wrote', PUBLIC_MANIFEST, `(${Object.keys(photos).length} photos)`);

  const tsBody =
    '/** Auto-generated by scripts/bcf/sync-bcf-cf-photo-manifest.mjs — do not edit by hand. */\n' +
    `export const BCF_PDP_CF_HERO_PHOTOS = ${JSON.stringify(photos, null, 2)} as const;\n` +
    `export type BcfPdpCfHeroPhotoEntry = (typeof BCF_PDP_CF_HERO_PHOTOS)[keyof typeof BCF_PDP_CF_HERO_PHOTOS];\n`;
  writeFileSync(GENERATED_TS, tsBody);
  console.log('Wrote', GENERATED_TS);
}

main();
