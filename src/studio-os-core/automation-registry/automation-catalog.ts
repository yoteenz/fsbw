export function getAutomationEntry(automationId: string): AutomationEntry | undefined {
  return buildAutomationCatalog().find((a) => a.automationId === automationId);
}

export function listAutomationsByCategory(category: AutomationCategory): AutomationEntry[] {
  return buildAutomationCatalog().filter((a) => a.category === category);
}

export function listAutomationsByStatus(status: AutomationStatus): AutomationEntry[] {
  return buildAutomationCatalog().filter((a) => a.status === status);
}

export function listAutomationsByRisk(risk: AutomationRiskLevel): AutomationEntry[] {
  return buildAutomationCatalog().filter((a) => a.riskLevel === risk);
}
