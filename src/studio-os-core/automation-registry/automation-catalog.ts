import type { AutomationCategory, AutomationEntry, AutomationRiskLevel, AutomationStatus } from './types';

function automation(
  partial: Pick<
    AutomationEntry,
    'automationId' | 'name' | 'description' | 'category' | 'owner' | 'department' | 'trigger'
  > &
    Partial<AutomationEntry>
): AutomationEntry {
  return {
    conditions: partial.conditions ?? [],
    actions: partial.actions ?? [],
    dependencies: partial.dependencies ?? [],
    permissions: partial.permissions ?? ['organization-admin'],
    organizations: partial.organizations ?? ['all'],
    status: partial.status ?? 'active',
    confidencePct: partial.confidencePct ?? 88,
    riskLevel: partial.riskLevel ?? 'low',
    approvalRequired: partial.approvalRequired ?? false,
    successRatePct: partial.successRatePct ?? 94,
    failureRatePct: partial.failureRatePct ?? 6,
    avgDurationMs: partial.avgDurationMs ?? 420,
    version: partial.version ?? '1.0.0',
    documentation: partial.documentation ?? [`docs/studio-os/${partial.category}.md`],
    executionCount: partial.executionCount ?? 0,
    registered: true,
    ...partial,
  };
}

