import type { PromptCategory, PromptEntry } from './types';

function prompt(
  partial: Pick<
    PromptEntry,
    'promptId' | 'name' | 'description' | 'purpose' | 'promptType' | 'category' | 'owner' | 'department' | 'associatedFeature'
  > &
    Partial<PromptEntry>
): PromptEntry {
  return {
    organizationScope: partial.organizationScope ?? ['all'],
    version: partial.version ?? '1.0.0',
    status: partial.status ?? 'active',
    dependencies: partial.dependencies ?? [],
    supportedModels: partial.supportedModels ?? ['gpt-4o', 'claude-sonnet'],
    variables: partial.variables ?? [],
    expectedOutput: partial.expectedOutput ?? 'Structured JSON or executive prose per prompt spec.',
    documentation: partial.documentation ?? [`docs/studio-os/${partial.category}.md`],
    lastUpdated: partial.lastUpdated ?? new Date().toISOString(),
    registered: true,
    qualityScorePct: partial.qualityScorePct ?? 88,
    testCount: partial.testCount ?? 0,
    ...partial,
  };
}

