export function getPromptEntry(promptId: string): PromptEntry | undefined {
  return buildPromptCatalog().find((p) => p.promptId === promptId);
}

export function listPromptsByCategory(category: PromptCategory): PromptEntry[] {
  return buildPromptCatalog().filter((p) => p.category === category);
}

export function listPromptsByFeature(feature: string): PromptEntry[] {
  const f = feature.toLowerCase();
  return buildPromptCatalog().filter(
    (p) => p.associatedFeature.toLowerCase().includes(f) || p.category.includes(f)
  );
}

export function listPromptsByStatus(status: PromptEntry['status']): PromptEntry[] {
  return buildPromptCatalog().filter((p) => p.status === status);
}
