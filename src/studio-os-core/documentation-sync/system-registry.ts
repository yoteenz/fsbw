function entry(
  partial: Omit<DocumentationSystemEntry, 'docPath'> & { id: string; label: string; purpose: string; overview: string }
): DocumentationSystemEntry {
  const { id, label, overview } = partial;
  return {
    ...partial,
    docPath: `docs/studio-os/${id}.md`,
    capabilities: partial.capabilities ?? [],
    howItWorks: partial.howItWorks ?? overview,
    whenUsed: partial.whenUsed ?? [],
    relatedSystems: partial.relatedSystems ?? [],
    exampleWorkflows: partial.exampleWorkflows ?? [],
    aliases: partial.aliases ?? [label.replace(/™/g, '').toLowerCase()],
    searchKeywords: partial.searchKeywords ?? [id.replace(/-/g, ' '), label.toLowerCase()],
  };
}

